/*
 * imu.h
 *
 *  IMU 传感器识别与数据采集驱动
 *  支持型号:
 *    - TDK IIM-42351   (WHO_AM_I = 0x6C @ 0x75)
 *    - TDK ICM-40608   (WHO_AM_I = 0x39 @ 0x75)
 *    - ST  LSM6DSOTR   (WHO_AM_I = 0x6C @ 0x0F)
 *
 *  说明: IIM-42351 与 LSM6DSO 的 WHO_AM_I 值同为 0x6C,
 *        但寄存器地址不同 (0x75 vs 0x0F), 据此区分两者。
 */

#ifndef IIC_IMU_H_
#define IIC_IMU_H_

#include "hal_data.h"

/* ======================================================================
 *  传感器类型枚举
 * ====================================================================== */
typedef enum
{
    IMU_SENSOR_NONE     = 0,   /* 未识别到 IMU              */
    IMU_SENSOR_IIM42351 = 1,   /* TDK IIM-42351             */
    IMU_SENSOR_ICM40608 = 2,   /* TDK ICM-40608             */
    IMU_SENSOR_LSM6DSO  = 3,   /* ST  LSM6DSO / LSM6DSOTR   */
} imu_sensor_t;

/* ======================================================================
 *  IMU 初始化: 自动识别芯片型号并完成基本配置
 *  返回: 识别到的传感器类型 (IMU_SENSOR_NONE 表示未识别)
 * ====================================================================== */
imu_sensor_t imu_init(void);

/* ======================================================================
 *  获取当前识别到的传感器类型
 * ====================================================================== */
imu_sensor_t imu_get_sensor(void);

/* ======================================================================
 *  读取三轴加速度 (单位: LSB, 未经量程换算)
 *  @param[out] acc  长度为 3 的数组, 依次存放 X / Y / Z 轴原始值
 *  @return 0 = 成功; -1 = 未识别到 IMU
 * ====================================================================== */
int32_t imu_get_acc(int16_t *acc);

#endif /* IIC_IMU_H_ */
